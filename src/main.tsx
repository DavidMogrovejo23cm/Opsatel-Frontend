import { StrictMode } from 'react'
import { createRoot } from 'react-dom/client'
import './index.css'
import './responsive.css'
import App from './App'

// Interceptor global en tiempo de ejecución: Reemplazo automático de ñ/Ñ por N en cualquier input del sistema
if (typeof window !== 'undefined') {
  window.addEventListener('input', (e) => {
    const target = e.target as HTMLInputElement | HTMLTextAreaElement | null;
    if (
      target &&
      (target.tagName === 'INPUT' || target.tagName === 'TEXTAREA') &&
      target.type !== 'password' &&
      target.type !== 'file'
    ) {
      if (typeof target.value === 'string' && /[ñÑ]/.test(target.value)) {
        const start = target.selectionStart;
        const end = target.selectionEnd;
        target.value = target.value.replace(/ñ/g, 'N').replace(/Ñ/g, 'N');
        if (start !== null && end !== null) {
          try { target.setSelectionRange(start, end); } catch (_) {}
        }
      }
    }
  }, true);
}

createRoot(document.getElementById('root')!).render(
  <StrictMode>
    <App />
  </StrictMode>,
)
